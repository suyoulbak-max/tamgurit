"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const root = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(__dirname, "..");
const context = { window: { SiteData: {} } };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root, "data/site.config.js"), "utf8"), context);
const config = context.window.SiteData.config;
const favicon = fs.readFileSync(path.join(root, "favicon.png"));
assert.equal(favicon.subarray(0, 8).toString("hex"), "89504e470d0a1a0a", "favicon must be a real PNG");
assert.equal(favicon.readUInt32BE(16), 192, "favicon width must be 192px");
assert.equal(favicon.readUInt32BE(20), 192, "favicon height must be 192px");
const fallbackIcon = fs.readFileSync(path.join(root, "favicon.ico"));
assert.equal(fallbackIcon.readUInt16LE(0), 0, "ICO reserved field");
assert.equal(fallbackIcon.readUInt16LE(2), 1, "ICO image type");
assert.equal(fallbackIcon.readUInt16LE(4), 1, "ICO entry count");
assert.equal(fallbackIcon[6], 192, "ICO width");
assert.equal(fallbackIcon[7], 192, "ICO height");
assert.equal(fallbackIcon.readUInt32LE(14), favicon.length, "ICO payload length");
assert.equal(fallbackIcon.readUInt32LE(18), 22, "ICO payload offset");
assert(fallbackIcon.subarray(22).equals(favicon), "ICO must contain the same brand image as PNG");
assert(!Object.hasOwn(config, "contactEmail"), "recipient mailbox must not be included in public settings");
assert(/^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/i.test(config.web3formsAccessKey), "a valid Web3Forms access key is required");
const shareUrl = new URL(config.shareImage, config.url + "/").href;
const shareImage = fs.readFileSync(path.join(root, config.shareImage));
assert.equal(shareImage.subarray(0, 8).toString("hex"), "89504e470d0a1a0a", "share asset must be a PNG");
assert.equal(shareImage.readUInt32BE(16), config.shareImageWidth, "share width must match the actual image");
assert.equal(shareImage.readUInt32BE(20), config.shareImageHeight, "share height must match the actual image");
const directories = ["about", "admin", "author", "categories", "columns", "contact", "disclaimer", "posts", "privacy", "sitemap", "terms"];
const htmlFiles = ["index.html", "404.html", ...directories.flatMap((dir) => fs.readdirSync(path.join(root, dir)).filter((name) => name.endsWith(".html")).map((name) => `${dir}/${name}`))];
const failures = [];
let links = 0;
for (const file of htmlFiles) {
  const html = fs.readFileSync(path.join(root, file), "utf8");
  assert(!/href=["']mailto:/i.test(html), `${file}: direct mailbox link remains`);
  assert(!html.includes("{{access_key}}") && !html.includes("{{owner_name}}"), `${file}: unresolved contact template`);
  const icons = Array.from(html.matchAll(/<link rel="icon" href="([^"]+)" type="image\/png" sizes="192x192">/g), match => match[1]);
  assert.equal(icons.length, 1, `${file}: must expose one search-compatible PNG favicon`);
  assert.equal(icons[0], "/favicon.png", `${file}: favicon must have a stable root URL`);
  if (html.includes("Static HTML generated by tools/build-static.cjs")) {
    const ogImages = Array.from(html.matchAll(/<meta property="og:image" content="([^"]+)">/g), (match) => match[1]);
    assert.deepEqual(ogImages, [shareUrl], `${file}: must expose exactly one crawlable share image`);
    assert(html.includes(`<meta name="twitter:image" content="${shareUrl}">`), `${file}: missing Twitter share image`);
    assert(html.includes('<meta name="twitter:card" content="summary_large_image">'), `${file}: missing large-image card`);
    for (const dimension of ["width", "height"]) {
      const value = config[dimension === "width" ? "shareImageWidth" : "shareImageHeight"];
      assert(html.includes(`<meta property="og:image:${dimension}" content="${value}">`), `${file}: incorrect share image ${dimension}`);
    }
  }
  for (const match of html.matchAll(/\b(?:href|src)=["']([^"']+)["']/g)) {
    const value = match[1].replace(/&amp;/g, "&");
    if (/^(?:[a-z]+:|\/\/|#)/i.test(value)) continue;
    const pathname = decodeURIComponent(value.split(/[?#]/)[0]);
    if (!pathname) continue;
    const target = pathname.startsWith("/") ? path.join(root, pathname) : path.resolve(root, path.dirname(file), pathname);
    links++;
    if (!fs.existsSync(target)) failures.push(`${file}: missing ${value}`);
  }
}
vm.runInContext(fs.readFileSync(path.join(root, "data/posts.js"), "utf8"), context);
const sitemap = fs.readFileSync(path.join(root, "sitemap.xml"), "utf8");
for (const post of context.window.SiteData.posts.filter((item) => item.ads === false)) {
  const html = fs.readFileSync(path.join(root, "posts", post.slug + ".html"), "utf8");
  assert(html.includes(post.content), `${post.slug}: source body must be fully prerendered`);
  assert(sitemap.includes(`/posts/${post.slug}.html</loc>`), `${post.slug}: missing sitemap entry`);
  assert(!/adsbygoogle\.js/.test(html), `${post.slug}: advertising loader present`);
}
assert.equal(failures.length, 0, failures.join("\n"));
console.log(`Site integrity PASS: ${htmlFiles.length} HTML files, ${links} local references, complete revised bodies and advertising exclusions.`);
