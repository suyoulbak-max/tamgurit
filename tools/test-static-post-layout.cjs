#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");
const assert = require("assert");
const vm = require("vm");
const { spawnSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const sandbox = { window: { SiteData: {} } };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root, "data/posts.js"), "utf8"), sandbox, { filename: "data/posts.js" });
const postsBySlug = new Map(sandbox.window.SiteData.posts.map((post) => [post.slug, post]));
const app = fs.readFileSync(path.join(root, "assets/js/app.js"), "utf8");
const stale = path.join(root, "posts", "__stale-generated-test.html");
fs.writeFileSync(stale, "<!-- Static HTML generated by tools/build-static.cjs test -->");
const built = spawnSync(process.execPath, [path.join(root, "tools", "build-static.cjs")], { cwd: root, encoding: "utf8" });
assert.strictEqual(built.status, 0, built.stderr || "static build failed");
assert(!fs.existsSync(stale), "build must remove obsolete generated pages");
const pages = fs.readdirSync(path.join(root, "posts"))
  .filter((name) => name.endsWith(".html") && !["index.html", "detail.html"].includes(name));

assert(pages.length > 0, "no generated post pages");
assert(
  app.includes('query("slug") || document.body.dataset.slug'),
  "post renderer must accept the clean page data-slug"
);
assert(
  app.includes('var canonicalPath = "posts/" + encodeURIComponent(post.slug) + ".html"'),
  "clean post renderer must preserve the clean canonical URL"
);

for (const name of pages) {
  const html = fs.readFileSync(path.join(root, "posts", name), "utf8");
  const slug = name.replace(/\.html$/, "");
  const post = postsBySlug.get(slug);
  assert(post, `${name}: missing source post`);
  assert(html.includes(`<body data-page="post-detail" data-slug="${slug}" data-prerendered="true">`), `${name}: missing route data`);
  assert(html.includes('<div id="app">'), `${name}: missing app mount`);
  assert(html.includes('class="article-layout"'), `${name}: missing article layout fallback`);
  assert(html.includes('class="article-body"'), `${name}: missing article body fallback`);
  assert(html.includes('class="aside"'), `${name}: missing sidebar fallback`);
  if (post.fullArticle) {
    assert(!html.includes('"@type":"FAQPage"'), `${name}: full article must not publish stale FAQ structured data`);
    assert((post.content.match(/<h2\b/gi) || []).length >= 4, `${name}: full article needs structured sections`);
  } else {
    assert(html.includes('class="comparison-table"'), `${name}: missing comparison fallback`);
    assert(html.includes('class="writing-steps"'), `${name}: missing writing-step fallback`);
    assert(html.includes('class="faq-list"'), `${name}: missing FAQ fallback`);
    assert(html.includes('"@type":"FAQPage"'), `${name}: missing FAQ structured data`);
  }
  assert((html.match(/class="article-brief/g) || []).length === 2, `${name}: missing toc/summary fallback`);
  assert(html.includes('../assets/js/app.js'), `${name}: missing shared renderer`);
  assert(html.includes('../assets/css/style.css'), `${name}: missing shared stylesheet`);
  assert(!html.includes('<style>'), `${name}: standalone CSS overrides shared design`);
  assert(html.includes(`<link rel="canonical" href="https://plus-literacy.co.kr/posts/${name}">`), `${name}: canonical changed`);
}

console.log(`Static post layout test passed: ${pages.length} pages`);
